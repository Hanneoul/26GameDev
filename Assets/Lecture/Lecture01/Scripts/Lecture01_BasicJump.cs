/*
 * ==============================================================================
 * [Unity] 2D 베이직 점프 및 물리/입력 시스템 상세 해설
 * ==============================================================================
 * 
 * 1. 핵심 개념 기초 해설 (초보자용)
 *    - Rigidbody2D (리지드바디 2D): 
 *      게임 오브젝트에 2차원 물리 법칙(중력, 질량, 마찰력 등)을 부여하는 핵심 컴포넌트임. 
 *      이 컴포넌트가 있어야 오브젝트가 중력에 의해 아래로 떨어지거나, 힘(Force)을 받아 
 *      위로 튀어오르는 등의 자연스러운 물리 움직임이 가능해짐.
 *    - Physics (물리 엔진): 
 *      유니티 내부에서 실시간으로 물체의 위치, 속도, 충돌 등을 계산해주는 시스템임.
 *      AddForce()를 통해 물리 엔진에 힘을 가하면 오브젝트가 가속도를 얻어 이동함.
 * 
 * 2. 유니티 라이프사이클 (Lifecycle)
 *    - Awake / Start: 
 *      게임이 시작될 때 단 한 번 호출되며, GetComponent<Rigidbody2D>() 같은 컴포넌트 
 *      참조를 미리 찾아두어(캐싱) 성능을 최적화하는 용도로 주로 사용됨.
 *    - Update: 
 *      화면이 갱신되는 매 프레임마다 호출됨. 주로 입력(키보드, 마우스) 감지나 실시간 상태 
 *      체크를 처리하기에 적합함.
 *    - OnMouseDown: 
 *      유니티의 빌트인 이벤트 함수 중 하나로, 해당 오브젝트의 콜라이더(Collider2D) 영역 안에서 
 *      마우스 클릭(또는 터치)이 발생했을 때 유니티 엔진이 자동으로 감지하여 호출해줌.
 * 
 * 3. 입력 처리 방식 비교: 이벤트 함수 vs 직접 함수 지정(Invoke)
 *    - 이벤트 함수 (예: OnMouseDown, OnCollisionEnter 등):
 *      유니티 엔진이 내부 규칙에 따라 특정 상황(클릭, 충돌 등)에 자동으로 호출해주는 방식임.
 *      * 장점: 코드가 짧고 별도의 세팅 없이 콜라이더만 있으면 즉시 동작하여 구현이 매우 직관적임.
 *      * 단점: 함수 이름이 정해져 있어 커스텀이 어렵고, 반드시 스크립트가 붙은 오브젝트에 
 *        Collider2D 컴포넌트가 필수적으로 존재해야만 작동함.
 *    - 직접 함수 지정 / 이벤트 시스템 (예: UI Button의 OnClick에 함수 연결 또는 Input System/Invoke):
 *      개발자가 직접 트리거 조건을 만들거나 UI 이벤트 리스너에 특정 함수를 등록하여 호출하는 방식임.
 *      * 장점: 유연성이 매우 높고, UI 버튼이나 다양한 입력 장치(키패드 등)와 결합하기 좋음.
 *      * 단점: 초기 연결 설정(인스펙터 바인딩 등)이 필요하여 약간의 추가 작업이 발생함.
 * ==============================================================================
 */

using UnityEngine;

public class Lecture01_BasicJump : MonoBehaviour
{
    // 2D 물리 연산을 제어하기 위한 Rigidbody2D 컴포넌트를 담을 변수 선언함
    Rigidbody2D rb;

    // 점프할 때 위로 가할 힘의 크기를 인스펙터 창에서 조절할 수 있도록 공개(public)로 선언함
    public float force = 500.0f;

    // Start 함수: 게임 오브젝트가 생성된 후 첫 번째 프레임 업데이트 전에 단 한 번 실행됨
    void Start()
    {
        // 이 오브젝트에 부착된 Rigidbody2D 컴포넌트를 찾아와서 rb 변수에 담아둠 (캐싱)
        rb = GetComponent<Rigidbody2D>();
    }

    // Update 함수: 화면이 렌더링되는 매 프레임마다 반복해서 호출됨
    void Update()
    {
        // 현재 이 예제에서는 매 프레임 처리할 로직이 없으므로 비어 있음
    }

    // OnMouseDown 함수: 마우스로 현재 오브젝트(콜라이더 영역)를 클릭했을 때 유니티가 자동 호출함
    private void OnMouseDown()
    {
        // x축은 0, y축은 1인 방향 벡터에 force 값을 곱해서 위쪽 방향의 힘 크기를 계산함
        Vector2 upForce = new Vector2(0.0f, 1.0f) * force;

        // 미리 찾아둔 Rigidbody2D에 위쪽 방향의 힘을 순간적으로 가해 점프(이동)시킴
        rb.AddForce(upForce);
    }
}